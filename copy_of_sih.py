def confidence_encode(x):
    x = str(x).lower().strip()
    if x == "h":
        return 2
    if x == "l":
        return 0
    if x == "n":
        return 1
    try:
        return float(x)
    except Exception:
        return 1

features["confidence_numeric"] = features["confidence"].apply(confidence_encode)
features["is_n20"] = features["satellite_source"].eq("VIIRS_N20").astype(int)
features["is_suomi_npp"] = features["satellite_source"].eq("VIIRS_SUOMI_NPP").astype(int)

# Seasonal windows (India-specific, weak-label signal only)
features["is_forest_fire_season"] = features["month"].isin([2, 3, 4, 5]).astype(int)
