def run_overpass_query(tag_clause, max_retries=2):
    """Try each mirror, with a couple of retries per mirror, before giving up."""
    query = f"[out:json][timeout:60];\n({tag_clause});\nout center;"

    for mirror in OVERPASS_MIRRORS:
        for attempt in range(max_retries):
            try:
                print(f"  Trying {mirror} (attempt {attempt + 1})...")
                resp = requests.get(
                    mirror, params={"data": query}, headers=headers, timeout=90
                )
                if resp.status_code == 200:
                    data = resp.json()
                    n = len(data.get("elements", []))
                    print(f"  Success: {n} elements")
                    return data.get("elements", [])
                else:
                    print(f"  HTTP {resp.status_code} from {mirror}")
            except Exception as e:
                print(f"  Failed on {mirror}: {e}")
            time.sleep(5)  # brief backoff before retry/next mirror
    return None


