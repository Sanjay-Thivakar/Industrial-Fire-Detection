# --- PATCH for Cell 12: better verification links + columns --------
#
# Fixes "empty land" confusion:
#   1. Default Google Maps links open at a wide, non-satellite zoom.
#      This switches to a close-in satellite/hybrid view.
#   2. Adds a second link showing BOTH the fire point and its matched
#      OSM facility on one map, so you can see the actual offset
#      distance instead of guessing from one point alone.
#   3. Surfaces facility match quality as its own column, so you can
#      sort/filter by "how good is this match" instead of relying on
#      eyeballing a possibly-outdated satellite photo.
#
# Run this instead of (or as a replacement block within) Cell 12.
# ---------------------------------------------------------------

def make_satellite_link(lat, lon, zoom=17):
    """Close-in satellite/hybrid view, much easier to actually see structures."""
    return f"https://www.google.com/maps/@{lat},{lon},{zoom}z/data=!3m1!1e3"


def make_dual_marker_link(fire_lat, fire_lon, facility_lat, facility_lon):
    """Shows the fire point and its matched facility as two markers,
    so you can see the real spatial relationship instead of guessing."""
    return (
        "https://www.google.com/maps/dir/?api=1"
        f"&origin={fire_lat},{fire_lon}"
        f"&destination={facility_lat},{facility_lon}"
        "&travelmode=walking"
    )


# Pull facility lat/lon back in (they exist in osm_df, joined by osm_id)
