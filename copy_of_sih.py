def assign_weak_label(row):
    near_facility = row["distance_to_facility_m"] <= 2000
    persistent = row["grid_active_days"] >= 3
    local_spike = (row["high_brightness_flag_local"] == 1) or (row["high_frp_flag_local"] == 1)

    has_landcover = row["landcover_class"] != "Unknown"
    built_up = row["landcover_class"] == "Built-up"
    forest = row["landcover_class"] == "Tree cover"
    cropland = row["landcover_class"] == "Cropland"

    if has_landcover:
        # Stricter rules when we know the land cover
        if near_facility and built_up and persistent and not local_spike:
            return "Persistent Thermal Source"
        if near_facility and built_up and local_spike:
            return "Industrial Fire"
        if forest and not near_facility and row["is_forest_fire_season"] == 1:
            return "Forest Fire"
        if cropland and not persistent and row["is_stubble_burning_season"] == 1:
            return "Agricultural Burning"
        return "Other/Unclassified"
    else:
        # FALLBACK: no land cover — use facility distance + persistence +
        # thermal anomaly + season only. Less precise, but non-degenerate.
        if near_facility and persistent and not local_spike:
            return "Persistent Thermal Source"
        if near_facility and local_spike:
            return "Industrial Fire"
        if not near_facility and local_spike and row["is_forest_fire_season"] == 1:
            return "Possible Forest Fire"
        if not near_facility and not persistent and row["is_stubble_burning_season"] == 1:
            return "Possible Agricultural Burning"
        return "Other/Unclassified"

features["weak_label"] = features.apply(assign_weak_label, axis=1)
