# --- CELL 10 (FIXED): WEAK LABELS + CLASSIFIER ----------------------
#
# FIX: the previous version required a specific land-cover match
# (Built-up / Tree cover / Cropland) to assign ANY class other than
# "Other/Unclassified". If land cover is unavailable, every row fell
# into one bucket — a degenerate, unlearnable target (which is what
# happened in your run: 634/634 "Other/Unclassified").
#
# This version uses land cover as a REFINEMENT when available, but
# falls back to facility-distance + persistence + thermal-anomaly
# rules alone when it isn't — so the classifier always has a real,
# non-degenerate multi-class target to learn from.
# ---------------------------------------------------------------

