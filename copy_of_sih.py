# Explicit match-quality tiering, so you can sort instead of eyeball
def match_quality(distance_km):
    if pd.isna(distance_km):
        return "No facility matched"
    if distance_km <= 0.5:
        return "Very close (<=500m) — should visually align"
    if distance_km <= 2.0:
        return "Near (<=2km) — may be offset in imagery"
    return "Far (>2km) — not actually a strong match"

review_df["match_quality"] = review_df["distance_to_facility_km"].apply(match_quality)

